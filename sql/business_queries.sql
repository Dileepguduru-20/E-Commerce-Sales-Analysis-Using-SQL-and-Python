-- Query 1: List all unique cities where customers are located
SELECT DISTINCT customer_city
FROM customers
ORDER BY customer_city;

-- Query 2: Count the number of orders placed in 2017
SELECT COUNT(order_id) AS orders_2017
FROM orders
WHERE YEAR(order_purchase_timestamp) = 2017;

-- Query 3: Find the total sales per category
SELECT 
    UPPER(pr.product_category) AS category,
    ROUND(SUM(p.payment_value), 2) AS total_sales
FROM products pr
JOIN order_items oi ON pr.product_id = oi.product_id
JOIN payments p ON p.order_id = oi.order_id
WHERE pr.product_category IS NOT NULL
GROUP BY pr.product_category
ORDER BY total_sales DESC;

-- Query 4: Calculate the percentage of orders that were paid in installments
SELECT 
    ROUND(SUM(CASE WHEN payment_installments >= 1 THEN 1 ELSE 0 END) * 100.0 / COUNT(*), 2) AS percentage_installments
FROM payments;

-- Query 5: Count the number of customers from each state
SELECT 
    customer_state,
    COUNT(customer_id) AS customer_count
FROM customers
GROUP BY customer_state
ORDER BY customer_count DESC;

