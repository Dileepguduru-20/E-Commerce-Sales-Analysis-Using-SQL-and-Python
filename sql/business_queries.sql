-- Query 11: Calculate the moving average of order values for each customer
WITH customer_orders AS (
    SELECT 
        o.customer_id,
        o.order_id,
        o.order_purchase_timestamp,
        p.payment_value,
        ROW_NUMBER() OVER (PARTITION BY o.customer_id ORDER BY o.order_purchase_timestamp) AS order_sequence
    FROM orders o
    JOIN payments p ON o.order_id = p.order_id
)
SELECT 
    customer_id,
    order_id,
    order_purchase_timestamp,
    payment_value,
    ROUND(AVG(payment_value) OVER (
        PARTITION BY customer_id 
        ORDER BY order_sequence 
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ), 2) AS moving_avg_3_orders
FROM customer_orders
WHERE customer_id IN (
    SELECT customer_id 
    FROM customer_orders 
    GROUP BY customer_id 
    HAVING COUNT(*) >= 3
)
ORDER BY customer_id, order_sequence;

-- Query 12: Calculate the cumulative sales per month for each year
WITH monthly_sales AS (
    SELECT 
        YEAR(order_purchase_timestamp) AS year,
        MONTH(order_purchase_timestamp) AS month,
        SUM(p.payment_value) AS monthly_revenue
    FROM orders o
    JOIN payments p ON o.order_id = p.order_id
    GROUP BY year, month
)
SELECT 
    year,
    month,
    ROUND(monthly_revenue, 2) AS monthly_revenue,
    ROUND(SUM(monthly_revenue) OVER (
        PARTITION BY year 
        ORDER BY month
    ), 2) AS cumulative_revenue
FROM monthly_sales
ORDER BY year, month;

-- Query 13: Calculate the year-over-year growth rate of total sales
WITH yearly_sales AS (
    SELECT 
        YEAR(order_purchase_timestamp) AS year,
        SUM(p.payment_value) AS total_sales
    FROM orders o
    JOIN payments p ON o.order_id = p.order_id
    GROUP BY year
)
SELECT 
    year,
    ROUND(total_sales, 2) AS total_sales,
    ROUND(LAG(total_sales) OVER (ORDER BY year), 2) AS previous_year_sales,
    ROUND(
        ((total_sales - LAG(total_sales) OVER (ORDER BY year)) * 100.0 / 
        LAG(total_sales) OVER (ORDER BY year)), 
        2
    ) AS yoy_growth_percentage
FROM yearly_sales
ORDER BY year;

-- Query 14: Calculate customer retention rate 
-- (percentage of customers who make another purchase within 6 months)
WITH first_purchases AS (
    SELECT 
        customer_id,
        MIN(order_purchase_timestamp) AS first_purchase_date
    FROM orders
    GROUP BY customer_id
),
repeat_purchases AS (
    SELECT DISTINCT
        fp.customer_id
    FROM first_purchases fp
    JOIN orders o ON fp.customer_id = o.customer_id
    WHERE o.order_purchase_timestamp > fp.first_purchase_date
        AND o.order_purchase_timestamp <= DATE_ADD(fp.first_purchase_date, INTERVAL 6 MONTH)
)
SELECT 
    COUNT(DISTINCT fp.customer_id) AS total_customers,
    COUNT(DISTINCT rp.customer_id) AS customers_with_repeat_purchase,
    ROUND(
        (COUNT(DISTINCT rp.customer_id) * 100.0 / COUNT(DISTINCT fp.customer_id)), 
        2
    ) AS retention_rate_percentage
FROM first_purchases fp
LEFT JOIN repeat_purchases rp ON fp.customer_id = rp.customer_id;

-- Query 15: Identify the top 3 customers who spent the most money in each year
WITH customer_yearly_spend AS (
    SELECT 
        YEAR(o.order_purchase_timestamp) AS year,
        o.customer_id,
        c.customer_city,
        c.customer_state,
        SUM(p.payment_value) AS total_spent
    FROM orders o
    JOIN payments p ON o.order_id = p.order_id
    JOIN customers c ON o.customer_id = c.customer_id
    GROUP BY year, o.customer_id, c.customer_city, c.customer_state
),
ranked_customers AS (
    SELECT 
        *,
        ROW_NUMBER() OVER (PARTITION BY year ORDER BY total_spent DESC) AS rank_in_year
    FROM customer_yearly_spend
)
SELECT 
    year,
    customer_id,
    customer_city,
    customer_state,
    ROUND(total_spent, 2) AS total_spent,
    rank_in_year
FROM ranked_customers
WHERE rank_in_year <= 3
ORDER BY year, rank_in_year;


