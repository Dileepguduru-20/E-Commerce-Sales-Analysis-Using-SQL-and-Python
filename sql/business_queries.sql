-- Query 6: Calculate the number of orders per month in 2018
SELECT 
    DATE_FORMAT(order_purchase_timestamp, '%Y-%m') AS month,
    COUNT(order_id) AS order_count
FROM orders
WHERE YEAR(order_purchase_timestamp) = 2018
GROUP BY month
ORDER BY month;

-- Query 7: Find the average number of products per order, grouped by customer city
SELECT 
    c.customer_city,
    ROUND(AVG(order_item_count), 2) AS avg_products_per_order
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
JOIN (
    SELECT order_id, COUNT(*) AS order_item_count
    FROM order_items
    GROUP BY order_id
) oi_counts ON o.order_id = oi_counts.order_id
GROUP BY c.customer_city
ORDER BY avg_products_per_order DESC
LIMIT 20;

-- Query 8: Calculate the percentage of total revenue contributed by each product category
WITH category_revenue AS (
    SELECT 
        UPPER(pr.product_category) AS category,
        SUM(p.payment_value) AS revenue
    FROM products pr
    JOIN order_items oi ON pr.product_id = oi.product_id
    JOIN payments p ON p.order_id = oi.order_id
    WHERE pr.product_category IS NOT NULL
    GROUP BY pr.product_category
),
total_revenue AS (
    SELECT SUM(payment_value) AS total
    FROM payments
)
SELECT 
    category,
    ROUND(revenue, 2) AS revenue,
    ROUND((revenue * 100.0 / total), 2) AS revenue_percentage
FROM category_revenue, total_revenue
ORDER BY revenue DESC;

-- Query 9: Identify the correlation between product price and number of times purchased
-- (This requires exporting data for statistical analysis in Python)
SELECT 
    oi.product_id,
    ROUND(AVG(oi.price), 2) AS avg_price,
    COUNT(oi.order_id) AS purchase_count
FROM order_items oi
GROUP BY oi.product_id
HAVING purchase_count > 5
ORDER BY purchase_count DESC
LIMIT 100;

-- Query 10: Calculate the total revenue generated by each seller, and rank them
SELECT 
    s.seller_id,
    s.seller_city,
    s.seller_state,
    COUNT(DISTINCT oi.order_id) AS total_orders,
    ROUND(SUM(p.payment_value), 2) AS total_revenue,
    RANK() OVER (ORDER BY SUM(p.payment_value) DESC) AS revenue_rank
FROM sellers s
JOIN order_items oi ON s.seller_id = oi.seller_id
JOIN payments p ON oi.order_id = p.order_id
GROUP BY s.seller_id, s.seller_city, s.seller_state
ORDER BY total_revenue DESC
LIMIT 50;

